"""Regenerate RESULTS_SUMMARY.md from the included UCI AI4I sample.

Usage: python make_results_summary.py [output path]

Trains once with core.train. Nothing is saved into ./models. The completion
checks save to a temporary folder that is removed afterwards.
"""
import sys
from pathlib import Path

import core
from completion_checks import completion_checks
from narrative import results_summary

ROOT = Path(__file__).parent
SAMPLE = ROOT / 'data' / 'ai4i2020.csv'
SOURCE_LABEL = 'UCI AI4I generated sample'
STATUS = {True: 'Passed', False: 'Failed', None: 'Not checked'}


def _versions(run):
    dependencies = core.run_metadata(run).get('dependencies') or {}
    return ' / '.join(f'{name} {version}' for name, version in sorted(dependencies.items())) or 'Unknown'


def build_summary(run, checks):
    """Return the Markdown text for a run and its completion check results."""
    counts = run['counts']
    lines = [
        '# SignalReady results summary',
        '',
        '> Generated file. Values are regenerated by `python make_results_summary.py` from `data/ai4i2020.csv`. '
        'Exact numbers can change with library versions.',
        '',
        f'- Software versions: {_versions(run)}',
        f'- Data source: {run.get("source_label", "Unknown legacy source")}',
        f'- Dataset fingerprint (SHA-256 of the cleaned rows): `{run["fingerprint"]}`',
        f'- Random seed: {run["seed"]}',
        f'- Rows after removing repeats: {counts["training"]} training / {counts["selection"]} selection / {counts["final check"]} final check',
        f'- Approved inputs: {"; ".join(run["features"])}',
        f'- Selected model: **{run["winner"]}** (highest F1 on the selection group; decision threshold 0.5)',
        '',
        '## Selection group (used to choose the model)',
        '',
        '| Model | Found | Missed | False alarms | F1 |',
        '|---|---:|---:|---:|---:|',
    ]
    for name, stats in run['validation'].items():
        lines.append(f'| {name} | {stats["Failures found"]} | {stats["Failures missed"]} | {stats["False alarms"]} | {stats["F1"]:.3f} |')
    lines += [
        '',
        '## Final check (reserved readings not used for training or selection)',
        '',
        '| Model | Found | Missed | False alarms | Correct normal | Detection rate | Precision | F1 |',
        '|---|---:|---:|---:|---:|---:|---:|---:|',
    ]
    for name, stats in run['test'].items():
        lines.append(f'| {name} | {stats["Failures found"]} | {stats["Failures missed"]} | {stats["False alarms"]} | '
                     f'{stats["Correct no-failure readings"]} | {stats["Failure detection rate"]:.1%} | '
                     f'{stats["Warnings that were correct"]:.1%} | {stats["F1"]:.3f} |')
    lines += [
        '',
        'Found means correctly flagged failures. Missed means failures without a warning. '
        'False alarms are warnings on readings labeled as no failure. Precision is the share of warnings that were correct.',
        '',
        '## What the results mean',
        '',
    ]
    lines += [f'- {sentence}' for sentence in results_summary(run)]
    lines += [
        '',
        '## Completion checks',
        '',
        '| Check | Result | Detail |',
        '|---|---|---|',
    ]
    for check in checks:
        lines.append(f'| {check["Check"]} | {STATUS[check["Passed"]]} | {check["Detail"].replace("|", "/")} |')
    lines += [
        '',
        '## Limitations',
        '',
        '- The AI4I 2020 readings are generated data. These results do not show performance on real equipment.',
        '- Random row splits evaluate this dataset only. They do not validate future time periods or unseen machines.',
        '- The models classify readings. They do not forecast when a breakdown will happen or provide calibrated failure probabilities.',
        '- Feature importance describes the fitted model. It does not identify physical causes or repairs.',
        '- The model was chosen on the selection group before the final check. It was not tuned or refit on final-check results.',
        '',
        'Dataset credit: AI4I 2020 Predictive Maintenance Dataset by S. Matzka / UCI Machine Learning Repository '
        '(https://doi.org/10.24432/C5HS5C) / CC BY 4.0.',
        '',
    ]
    return '\n'.join(lines)


def main(out_path=ROOT / 'RESULTS_SUMMARY.md'):
    df = core.read_csv(SAMPLE.read_bytes())
    run = core.train(df, source_label=SOURCE_LABEL)
    checks = completion_checks(df, run, repeat=True)
    Path(out_path).write_text(build_summary(run, checks), encoding='utf-8')
    return run, checks


if __name__ == '__main__':
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'RESULTS_SUMMARY.md'
    _, results = main(target)
    print(f'Wrote {target}')
    for item in results:
        print(f'{STATUS[item["Passed"]]:>12}  {item["Check"]}')
